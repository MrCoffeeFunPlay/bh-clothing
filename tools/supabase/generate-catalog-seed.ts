// Writes the SQL that copies the current catalogue (src/catalog.ts) into Supabase, unchanged.
// Usage: node tools/supabase/generate-catalog-seed.ts > supabase/migrations/<timestamp>_seed_catalog.sql
import { categories, products } from "../../src/catalog.ts";

const q = (value: string | null | undefined) => value === null || value === undefined ? "null" : `'${value.replace(/'/g, "''")}'`;
const n = (value: number | null | undefined) => typeof value === "number" && Number.isFinite(value) ? String(value) : "null";
const arr = (values: string[] | undefined) => values?.length ? `array[${values.map(q).join(", ")}]::text[]` : "'{}'::text[]";
const slug = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const out: string[] = [
  "-- BH Clothing: copy of the catalogue that was live in src/catalog.ts, generated by tools/supabase/generate-catalog-seed.ts.",
  "-- Same products, descriptions, colours, images, sizes and prices; products without a price stay unpublished.",
  "-- No stock quantities are created.",
  "",
  "insert into public.categories (slug, name, description, image_path, sort_order) values",
  categories.map(([name, description, image], index) => `  (${q(slug(name))}, ${q(name)}, ${q(description)}, ${q(image)}, ${(index + 1) * 10})`).join(",\n") + ";",
  "",
];

for (const [index, product] of products.entries()) {
  const sale = product.sale;
  out.push(
    `insert into public.products (id, slug, name, category_slug, description, tag, sizes, fabric_weights, price_ils, price_usd, lookbook_images,`,
    `  sale_enabled, sale_title, sale_kind, sale_value, sale_currency, sale_starts_at, sale_ends_at, active, sort_order)`,
    `overriding system value values (${product.id}, ${q(slug(product.name))}, ${q(product.name)}, ${q(slug(product.category))}, ${q(product.description ?? "")}, ${q(product.tag)},`,
    `  ${arr(product.sizes)}, ${arr(product.cottonWeights)}, ${n(product.prices?.ILS)}, ${n(product.prices?.USD)}, ${arr(product.lookbookImages)},`,
    `  ${sale?.enabled ? "true" : "false"}, ${q(sale?.title ?? "")}, ${q(sale?.kind ?? "percent")}, ${n(sale?.value ?? 0)}, ${q(sale?.currency ?? "ILS")}, ${q(sale?.startsAt || null)}, ${q(sale?.endsAt || null)}, true, ${(index + 1) * 10});`,
  );
  const colours = Object.keys(product.colorImages ?? {});
  out.push(
    "insert into public.product_colours (product_id, name, hex, front_image, back_image, sort_order) values",
    colours.map((colour, order) => `  (${product.id}, ${q(colour)}, ${q(product.colorHexes?.[colour] ?? "#8d8275")}, ${q(product.colorImages![colour])}, ${q(product.backImages?.[colour] ?? null)}, ${order})`).join(",\n") + ";",
  );
  const weights = product.cottonWeights ?? [];
  if (weights.length) {
    out.push(
      "insert into public.product_weight_prices (product_id, weight, price_ils, price_usd, sale_price_ils, sale_price_usd, colours) values",
      weights.map(weight => {
        const price = product.gsmPrices?.[weight]; const salePrice = product.gsmSalePrices?.[weight];
        return `  (${product.id}, ${q(weight)}, ${n(price?.ILS)}, ${n(price?.USD)}, ${n(salePrice?.ILS)}, ${n(salePrice?.USD)}, ${arr(product.weightColors?.[weight] ?? colours)})`;
      }).join(",\n") + ";",
    );
  }
  out.push("");
}

out.push("select setval(pg_get_serial_sequence('public.products', 'id'), (select max(id) from public.products));", "");
process.stdout.write(out.join("\n"));
