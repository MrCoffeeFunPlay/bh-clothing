  for update to authenticated using (bucket_id = 'product-images' and (select public.is_catalog_admin()))
  with check (bucket_id = 'product-images' and (select public.is_catalog_admin()));
create policy "Admins delete product images" on storage.objects
  for delete to authenticated using (bucket_id = 'product-images' and (select public.is_catalog_admin()));
