-- BH Clothing, phase 1: a live catalogue that the owner manages, with admin access enforced by the database.
--
-- Customers (anon or signed in) can only read active categories and products. Only users listed in
-- public.catalog_admins can create, change or remove catalogue data or upload product images. Admins are added
-- by the owner in the Supabase SQL editor; there is no way to become an admin from the website.
--
-- Not part of this phase: orders, payments, stock quantities, coupons and customer accounts.

-- ---------------------------------------------------------------------------------------------------------------
-- Admins
-- ---------------------------------------------------------------------------------------------------------------
create table public.catalog_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  note text,
  created_at timestamptz not null default now()
);

alter table public.catalog_admins enable row level security;

-- A signed-in user may see whether they themselves are an admin. Nobody can add, change or remove admins through
-- the API: there are deliberately no insert/update/delete policies or grants.
create policy "Users can see their own admin row" on public.catalog_admins
  for select to authenticated using (user_id = (select auth.uid()));

revoke all on table public.catalog_admins from anon, authenticated;
grant select on table public.catalog_admins to authenticated;

create function public.is_catalog_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.catalog_admins where user_id = (select auth.uid()));
$$;

revoke all on function public.is_catalog_admin() from public;
grant execute on function public.is_catalog_admin() to anon, authenticated;

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------------------------------------------
-- Catalogue
-- ---------------------------------------------------------------------------------------------------------------
create table public.categories (
  slug text primary key check (slug ~ '^[a-z0-9-]+$'),
  name text not null unique check (length(trim(name)) > 0),
  description text not null default '',
  image_path text,
  sort_order integer not null default 0,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.products (
  id integer generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null check (length(trim(name)) > 0),
  category_slug text not null references public.categories (slug) on update cascade,
  description text not null default '',
  tag text,
  sizes text[] not null default '{}',
  -- Tees can be sold in 220 GSM and/or 260 GSM; prices and colours per weight live in product_weight_prices.
  fabric_weights text[] not null default '{}' check (fabric_weights <@ array['220g', '260g']),
  -- Prices for products without fabric weights. Null means "not published": the product cannot be bought.
  price_ils numeric(10, 2) check (price_ils > 0),
  price_usd numeric(10, 2) check (price_usd > 0),
  lookbook_images text[] not null default '{}',
  -- Optional timed product sale (percentage, or a fixed amount in one currency).
  sale_enabled boolean not null default false,
  sale_title text not null default '',
  sale_kind text not null default 'percent' check (sale_kind in ('percent', 'amount')),
  sale_value numeric(10, 2) not null default 0 check (sale_value >= 0),
  sale_currency text not null default 'ILS' check (sale_currency in ('ILS', 'USD')),
  sale_starts_at timestamptz,
  sale_ends_at timestamptz,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (sale_kind <> 'percent' or sale_value <= 100),
  check (not sale_enabled or sale_value > 0),
  check (sale_starts_at is null or sale_ends_at is null or sale_ends_at > sale_starts_at)
);

create index products_category_slug_idx on public.products (category_slug);

-- One row per colour: swatch and the front/back images for that colour.
create table public.product_colours (
  product_id integer not null references public.products (id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  hex text not null default '#8d8275' check (hex ~ '^#[0-9a-fA-F]{6}$'),
  front_image text not null check (length(trim(front_image)) > 0),
  back_image text,
  sort_order integer not null default 0,
  primary key (product_id, name)
);

-- One row per fabric weight: original and fixed sale prices in both currencies, and the colours sold in that weight.
-- A variation is colour x fabric weight x size; this phase stores no stock quantities.
create table public.product_weight_prices (
  product_id integer not null references public.products (id) on delete cascade,
  weight text not null check (weight in ('220g', '260g')),
  price_ils numeric(10, 2) check (price_ils > 0),
  price_usd numeric(10, 2) check (price_usd > 0),
  sale_price_ils numeric(10, 2) check (sale_price_ils is null or (sale_price_ils > 0 and price_ils is not null and sale_price_ils < price_ils)),
  sale_price_usd numeric(10, 2) check (sale_price_usd is null or (sale_price_usd > 0 and price_usd is not null and sale_price_usd < price_usd)),
  colours text[] not null default '{}',
  primary key (product_id, weight)
);

create trigger categories_updated_at before update on public.categories
  for each row execute function public.set_updated_at();
create trigger products_updated_at before update on public.products
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------------------------------------------
-- Row level security: everyone reads active data; only admins write.
-- ---------------------------------------------------------------------------------------------------------------
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.product_colours enable row level security;
alter table public.product_weight_prices enable row level security;

create policy "Read active categories" on public.categories
  for select to anon, authenticated using (active or (select public.is_catalog_admin()));
create policy "Read active products" on public.products
  for select to anon, authenticated using (active or (select public.is_catalog_admin()));
create policy "Read colours of visible products" on public.product_colours
  for select to anon, authenticated using (
    exists (select 1 from public.products p where p.id = product_id and (p.active or (select public.is_catalog_admin())))
  );
create policy "Read prices of visible products" on public.product_weight_prices
  for select to anon, authenticated using (
    exists (select 1 from public.products p where p.id = product_id and (p.active or (select public.is_catalog_admin())))
  );

create policy "Admins insert categories" on public.categories for insert to authenticated with check ((select public.is_catalog_admin()));
create policy "Admins update categories" on public.categories for update to authenticated using ((select public.is_catalog_admin())) with check ((select public.is_catalog_admin()));
create policy "Admins delete categories" on public.categories for delete to authenticated using ((select public.is_catalog_admin()));
create policy "Admins insert products" on public.products for insert to authenticated with check ((select public.is_catalog_admin()));
create policy "Admins update products" on public.products for update to authenticated using ((select public.is_catalog_admin())) with check ((select public.is_catalog_admin()));
create policy "Admins delete products" on public.products for delete to authenticated using ((select public.is_catalog_admin()));
create policy "Admins insert colours" on public.product_colours for insert to authenticated with check ((select public.is_catalog_admin()));
create policy "Admins update colours" on public.product_colours for update to authenticated using ((select public.is_catalog_admin())) with check ((select public.is_catalog_admin()));
create policy "Admins delete colours" on public.product_colours for delete to authenticated using ((select public.is_catalog_admin()));
create policy "Admins insert prices" on public.product_weight_prices for insert to authenticated with check ((select public.is_catalog_admin()));
create policy "Admins update prices" on public.product_weight_prices for update to authenticated using ((select public.is_catalog_admin())) with check ((select public.is_catalog_admin()));
create policy "Admins delete prices" on public.product_weight_prices for delete to authenticated using ((select public.is_catalog_admin()));

-- Visitors only ever get read access; signed-in users get write grants, which the policies above limit to admins.
revoke all on table public.categories, public.products, public.product_colours, public.product_weight_prices from anon, authenticated;
grant select on table public.categories, public.products, public.product_colours, public.product_weight_prices to anon, authenticated;
grant insert, update, delete on table public.categories, public.products, public.product_colours, public.product_weight_prices to authenticated;
grant usage on sequence public.products_id_seq to authenticated;

-- ---------------------------------------------------------------------------------------------------------------
-- Saving a product: one call, one transaction, so a product is never left half-saved.
-- Runs with the caller's rights (security invoker), so the policies above still apply on top of the explicit check.
-- ---------------------------------------------------------------------------------------------------------------
create function public.admin_save_product(product jsonb)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  saved_id integer := nullif(product ->> 'id', '')::integer;
  base_slug text;
  colour_names text[];
begin
  if not public.is_catalog_admin() then
    raise exception 'Only an authorised BH admin can change the catalogue.' using errcode = '42501';
  end if;

  if saved_id is not null then
    update public.products set
      name = trim(product ->> 'name'),
      category_slug = product ->> 'category_slug',
      description = coalesce(product ->> 'description', ''),
      tag = nullif(product ->> 'tag', ''),
      sizes = coalesce((select array_agg(value) from jsonb_array_elements_text(product -> 'sizes')), '{}'),
      fabric_weights = coalesce((select array_agg(value) from jsonb_array_elements_text(product -> 'fabric_weights')), '{}'),
      price_ils = nullif(product ->> 'price_ils', '')::numeric,
      price_usd = nullif(product ->> 'price_usd', '')::numeric,
      lookbook_images = coalesce((select array_agg(value) from jsonb_array_elements_text(product -> 'lookbook_images')), '{}'),
      sale_enabled = coalesce((product ->> 'sale_enabled')::boolean, false),
      sale_title = coalesce(product ->> 'sale_title', ''),
      sale_kind = coalesce(product ->> 'sale_kind', 'percent'),
      sale_value = coalesce(nullif(product ->> 'sale_value', '')::numeric, 0),
      sale_currency = coalesce(product ->> 'sale_currency', 'ILS'),
      sale_starts_at = nullif(product ->> 'sale_starts_at', '')::timestamptz,
      sale_ends_at = nullif(product ->> 'sale_ends_at', '')::timestamptz,
      active = coalesce((product ->> 'active')::boolean, true)
    where id = saved_id
    returning id into saved_id;
    if saved_id is null then
      raise exception 'This product no longer exists.' using errcode = 'P0002';
    end if;
  else
    base_slug := trim(both '-' from lower(regexp_replace(coalesce(product ->> 'name', ''), '[^a-zA-Z0-9]+', '-', 'g')));
    if base_slug = '' then base_slug := 'product'; end if;
    if exists (select 1 from public.products where slug = base_slug) then
      base_slug := base_slug || '-' || substr(md5(random()::text), 1, 5);
    end if;
    insert into public.products (slug, name, category_slug, description, tag, sizes, fabric_weights, price_ils, price_usd,
      lookbook_images, sale_enabled, sale_title, sale_kind, sale_value, sale_currency, sale_starts_at, sale_ends_at, active, sort_order)
    values (
      base_slug,
      trim(product ->> 'name'),
      product ->> 'category_slug',
      coalesce(product ->> 'description', ''),
      nullif(product ->> 'tag', ''),
      coalesce((select array_agg(value) from jsonb_array_elements_text(product -> 'sizes')), '{}'),
      coalesce((select array_agg(value) from jsonb_array_elements_text(product -> 'fabric_weights')), '{}'),
      nullif(product ->> 'price_ils', '')::numeric,
      nullif(product ->> 'price_usd', '')::numeric,
      coalesce((select array_agg(value) from jsonb_array_elements_text(product -> 'lookbook_images')), '{}'),
      coalesce((product ->> 'sale_enabled')::boolean, false),
      coalesce(product ->> 'sale_title', ''),
      coalesce(product ->> 'sale_kind', 'percent'),
      coalesce(nullif(product ->> 'sale_value', '')::numeric, 0),
      coalesce(product ->> 'sale_currency', 'ILS'),
      nullif(product ->> 'sale_starts_at', '')::timestamptz,
      nullif(product ->> 'sale_ends_at', '')::timestamptz,
      coalesce((product ->> 'active')::boolean, true),
      coalesce((select max(sort_order) + 10 from public.products), 10)
    )
    returning id into saved_id;
  end if;

  delete from public.product_colours c where c.product_id = saved_id;
  insert into public.product_colours (product_id, name, hex, front_image, back_image, sort_order)
  select saved_id, trim(c ->> 'name'), coalesce(nullif(c ->> 'hex', ''), '#8d8275'), c ->> 'front_image',
         nullif(c ->> 'back_image', ''), (n - 1)::integer
  from jsonb_array_elements(coalesce(product -> 'colours', '[]'::jsonb)) with ordinality as t (c, n);

  select coalesce(array_agg(c.name), '{}') into colour_names from public.product_colours c where c.product_id = saved_id;
  if cardinality(colour_names) = 0 then
    raise exception 'Add at least one colour with a front image.' using errcode = '23514';
  end if;

  delete from public.product_weight_prices w where w.product_id = saved_id;
  insert into public.product_weight_prices (product_id, weight, price_ils, price_usd, sale_price_ils, sale_price_usd, colours)
  select saved_id, w ->> 'weight',
         nullif(w ->> 'price_ils', '')::numeric, nullif(w ->> 'price_usd', '')::numeric,
         nullif(w ->> 'sale_price_ils', '')::numeric, nullif(w ->> 'sale_price_usd', '')::numeric,
         coalesce((select array_agg(value) from jsonb_array_elements_text(w -> 'colours')), '{}')
  from jsonb_array_elements(coalesce(product -> 'weight_prices', '[]'::jsonb)) as t (w);

  if exists (
    select 1 from public.product_weight_prices w
    where w.product_id = saved_id and not (w.colours <@ colour_names)
  ) then
    raise exception 'A fabric weight lists a colour that the product does not have.' using errcode = '23514';
  end if;

  return saved_id;
end;
$$;

revoke all on function public.admin_save_product(jsonb) from public, anon;
grant execute on function public.admin_save_product(jsonb) to authenticated;

-- ---------------------------------------------------------------------------------------------------------------
-- Product images: a public bucket (anyone can view a file by its URL); only admins can upload, replace or delete.
-- ---------------------------------------------------------------------------------------------------------------
